-- Esquema PostgreSQL (Supabase) de la plataforma de reservas.
--
-- Las tablas viven en el esquema privado "reservas" y NO en "public": Supabase
-- publica automáticamente "public" mediante su API REST, y estas tablas guardan
-- hashes de contraseñas, comprobantes y datos personales. Solo la API de la
-- aplicación accede a ellas, con su propio usuario de base de datos.
CREATE SCHEMA IF NOT EXISTS reservas;
SET search_path TO reservas;

-- Reemplaza a ON UPDATE CURRENT_TIMESTAMP de MySQL.
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE roles (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id SMALLINT NOT NULL REFERENCES roles (id),
  first_name VARCHAR(80) NOT NULL,
  last_name VARCHAR(80) NOT NULL,
  email VARCHAR(160) NOT NULL,
  phone VARCHAR(30),
  whatsapp_opt_in_at TIMESTAMPTZ,
  password_hash VARCHAR(255) NOT NULL,
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- MySQL comparaba sin distinguir mayúsculas; aquí lo garantiza el índice.
CREATE UNIQUE INDEX uq_users_email ON users (lower(email));
CREATE INDEX idx_users_role ON users (role_id);

CREATE TABLE password_reset_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id),
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_password_reset_tokens_expiry ON password_reset_tokens (user_id, expires_at, used_at);

CREATE TABLE tenants (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  slug VARCHAR(80) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?$'),
  legal_name VARCHAR(160) NOT NULL,
  display_name VARCHAR(160) NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'TRIAL' CHECK (status IN ('TRIAL', 'ACTIVE', 'SUSPENDED', 'CANCELLED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE tenant_memberships (
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  user_id BIGINT NOT NULL REFERENCES users (id),
  role VARCHAR(14) NOT NULL CHECK (role IN ('OWNER', 'ADMIN', 'BARBER', 'RECEPTIONIST')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, user_id)
);
CREATE INDEX idx_tenant_memberships_user ON tenant_memberships (user_id, is_active);

CREATE TABLE platform_administrators (
  user_id BIGINT PRIMARY KEY REFERENCES users (id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE tenant_settings (
  tenant_id UUID PRIMARY KEY REFERENCES tenants (id),
  business_name VARCHAR(160) NOT NULL,
  address VARCHAR(255) NOT NULL,
  city VARCHAR(120) NOT NULL,
  country VARCHAR(120) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  whatsapp VARCHAR(30) NOT NULL,
  hours_text VARCHAR(255) NOT NULL,
  maps_url VARCHAR(2048),
  instagram_url VARCHAR(2048),
  facebook_url VARCHAR(2048),
  payment_qr_url VARCHAR(2048),
  logo_url VARCHAR(2048),
  cover_url VARCHAR(2048),
  description TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE service_categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  name VARCHAR(80) NOT NULL,
  slug VARCHAR(80) NOT NULL,
  description VARCHAR(255),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_service_categories_tenant_name ON service_categories (tenant_id, lower(name));
CREATE UNIQUE INDEX uq_service_categories_tenant_slug ON service_categories (tenant_id, slug);

CREATE TABLE services (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  category_id INTEGER NOT NULL REFERENCES service_categories (id),
  name VARCHAR(120) NOT NULL,
  description TEXT,
  price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
  duration_minutes SMALLINT NOT NULL CHECK (duration_minutes > 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_services_tenant_name ON services (tenant_id, lower(name));
CREATE INDEX idx_services_category_active ON services (category_id, is_active);
CREATE INDEX idx_services_tenant_active ON services (tenant_id, is_active);

CREATE TABLE barbers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  user_id BIGINT UNIQUE REFERENCES users (id),
  display_name VARCHAR(120) NOT NULL,
  bio TEXT,
  photo_url VARCHAR(2048),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_barbers_tenant_active ON barbers (tenant_id, is_active);

CREATE TABLE barber_services (
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  barber_id BIGINT NOT NULL REFERENCES barbers (id),
  service_id BIGINT NOT NULL REFERENCES services (id),
  PRIMARY KEY (barber_id, service_id)
);
CREATE INDEX idx_barber_services_service ON barber_services (service_id);
CREATE INDEX idx_barber_services_tenant ON barber_services (tenant_id, barber_id, service_id);

CREATE TABLE barber_working_hours (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  barber_id BIGINT NOT NULL REFERENCES barbers (id),
  weekday SMALLINT NOT NULL CHECK (weekday BETWEEN 1 AND 7),
  start_time TIME NOT NULL,
  end_time TIME NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (barber_id, weekday, start_time, end_time),
  CHECK (start_time < end_time)
);
CREATE INDEX idx_barber_working_hours_tenant ON barber_working_hours (tenant_id);

CREATE TABLE schedule_blocks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  barber_id BIGINT NOT NULL REFERENCES barbers (id),
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  reason VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (starts_at < ends_at)
);
CREATE INDEX idx_schedule_blocks_range ON schedule_blocks (barber_id, starts_at, ends_at);
CREATE INDEX idx_schedule_blocks_tenant ON schedule_blocks (tenant_id);

CREATE TABLE appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  client_id BIGINT NOT NULL REFERENCES users (id),
  barber_id BIGINT NOT NULL REFERENCES barbers (id),
  service_id BIGINT NOT NULL REFERENCES services (id),
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
  payment_reference UUID,
  payment_proof_url VARCHAR(2048),
  payment_amount NUMERIC(10, 2),
  cancellation_reason VARCHAR(255),
  admin_notes TEXT,
  cancelled_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  updated_by BIGINT REFERENCES users (id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (starts_at < ends_at)
);
CREATE INDEX idx_appointments_service ON appointments (service_id);
CREATE INDEX idx_appointments_barber_range ON appointments (barber_id, starts_at, ends_at);
CREATE INDEX idx_appointments_client_history ON appointments (client_id, starts_at);
CREATE INDEX idx_appointments_updated_by ON appointments (updated_by);
CREATE INDEX idx_appointments_payment_reference ON appointments (payment_reference);
CREATE INDEX idx_appointments_tenant_range ON appointments (tenant_id, starts_at, ends_at);

CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  user_id BIGINT NOT NULL REFERENCES users (id),
  appointment_id BIGINT REFERENCES appointments (id),
  type VARCHAR(40) NOT NULL,
  title VARCHAR(160) NOT NULL,
  message TEXT NOT NULL,
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notifications_appointment ON notifications (appointment_id);
CREATE INDEX idx_notifications_user_status ON notifications (user_id, read_at, created_at);
CREATE INDEX idx_notifications_tenant_user ON notifications (tenant_id, user_id, read_at);

CREATE TABLE payment_proofs (
  id UUID PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  client_id BIGINT NOT NULL REFERENCES users (id),
  storage_key VARCHAR(255) NOT NULL UNIQUE,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_payment_proofs_owner_status ON payment_proofs (client_id, used_at, created_at);
CREATE INDEX idx_payment_proofs_tenant_owner ON payment_proofs (tenant_id, client_id, used_at);

CREATE TABLE reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  client_id BIGINT NOT NULL REFERENCES users (id),
  appointment_id BIGINT UNIQUE REFERENCES appointments (id),
  barber_id BIGINT REFERENCES barbers (id),
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment VARCHAR(1500) NOT NULL,
  is_visible BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_reviews_client ON reviews (client_id);
CREATE INDEX idx_reviews_barber ON reviews (barber_id);
CREATE INDEX idx_reviews_visible_created ON reviews (is_visible, created_at);
CREATE INDEX idx_reviews_tenant_visible ON reviews (tenant_id, is_visible, created_at);

CREATE TABLE reminder_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id),
  appointment_id BIGINT NOT NULL REFERENCES appointments (id),
  channel VARCHAR(10) NOT NULL CHECK (channel IN ('EMAIL', 'IN_APP', 'WHATSAPP')),
  reminder_type VARCHAR(4) NOT NULL CHECK (reminder_type IN ('24H', '2H')),
  scheduled_at TIMESTAMPTZ NOT NULL,
  sent_at TIMESTAMPTZ,
  status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'CANCELLED')),
  attempts SMALLINT NOT NULL DEFAULT 0,
  last_error VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_reminder_jobs_unique_delivery UNIQUE (appointment_id, channel, reminder_type)
);
CREATE INDEX idx_reminder_jobs_pending ON reminder_jobs (status, scheduled_at);
CREATE INDEX idx_reminder_jobs_tenant_pending ON reminder_jobs (tenant_id, status, scheduled_at);

DO $$
DECLARE
  target TEXT;
BEGIN
  FOREACH target IN ARRAY ARRAY['users', 'tenants', 'tenant_memberships', 'tenant_settings', 'service_categories', 'services', 'barbers', 'appointments', 'reminder_jobs'] LOOP
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$I FOR EACH ROW EXECUTE FUNCTION touch_updated_at()', target);
  END LOOP;
END;
$$;
