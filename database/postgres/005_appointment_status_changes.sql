-- Historial de cambios de estado de cada cita: quién la marcó como atendida,
-- no asistida o cancelada, cuándo, y las correcciones posteriores con su motivo.
-- Permite que el barbero deshaga un error durante unos minutos y que el dueño
-- corrija después dejando constancia.
SET search_path TO reservas;

CREATE TABLE appointment_status_changes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id UUID NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  appointment_id BIGINT NOT NULL REFERENCES appointments (id) ON DELETE CASCADE,
  from_status VARCHAR(12) NOT NULL,
  to_status VARCHAR(12) NOT NULL,
  -- CHANGE: cambio normal · UNDO: el barbero deshizo su cambio · CORRECTION: el dueño lo corrigió
  kind VARCHAR(12) NOT NULL CHECK (kind IN ('CHANGE', 'UNDO', 'CORRECTION')),
  reason VARCHAR(255),
  changed_by BIGINT REFERENCES users (id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_appointment_status_changes_appointment ON appointment_status_changes (tenant_id, appointment_id, created_at DESC);
